#!/usr/bin/env python3
"""Rebuild the recovered MaiaScript apps and their firmware resource headers."""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def main():
    for app in ('scicalc', 'alarm'):
        module = ROOT / 'examples/modules' / app / (app + '.mobj')
        subprocess.run([str(ROOT / 'maiascript/bin/maiasc'),
                        str(ROOT / 'maiascript/apps' / app / 'main.ms'),
                        '-I', str(ROOT / 'maiascript/lib'), '-o', str(module)], check=True)
        write_header(module, app)

    subprocess.run(["make", "-C", str(ROOT / "examples/modules/desktop")], check=True)
    write_header(ROOT / "examples/modules/desktop/desktop.mobj", "desktop")


def write_header(module, app):
    data = module.read_bytes()
    if data[:4] != b'\x7fELF':
        raise RuntimeError(f'{module}: compiler did not produce ELF')
    lines = ['/* Generated by scripts/build_maia_apps.py. */', '#pragma once',
             f'static const unsigned char {app}_mobj[] = {{']
    for i in range(0, len(data), 12):
        lines.append('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i+12]) + ',')
    lines.extend(['};', f'static const unsigned int {app}_mobj_len = {len(data)};', ''])
    (ROOT / 'include/maia/exec' / (app + '_mobj.h')).write_text('\n'.join(lines))
    print(f'{app}: {len(data)} bytes; firmware header regenerated')


if __name__ == '__main__':
    main()
