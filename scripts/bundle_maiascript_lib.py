#!/usr/bin/env python3
import os
import sys

def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    lib_dir = os.path.join(repo_root, "maiascript", "lib")
    out_header = os.path.join(repo_root, "include", "maia", "exec", "maiascript_lib_bundle.h")

    if not os.path.exists(lib_dir):
        print(f"Error: {lib_dir} does not exist", file=sys.stderr)
        sys.exit(1)

    files_to_bundle = []
    for root, _, files in os.walk(lib_dir):
        for f in files:
            if f.endswith(".ms"):
                full_path = os.path.join(root, f)
                rel_path = os.path.relpath(full_path, lib_dir)
                files_to_bundle.append((rel_path, full_path))

    # Include installable application sources at /sd/<name>.ms.
    for name in ("notes", "scicalc", "alarm"):
        app_source = os.path.join(repo_root, "maiascript", "apps", name, "main.ms")
        if os.path.exists(app_source):
            files_to_bundle.append(("../" + name + ".ms", app_source))

    files_to_bundle.sort(key=lambda x: x[0])

    lines = []
    lines.append("// Auto-generated by scripts/bundle_maiascript_lib.py - DO NOT EDIT MANUALLY")
    lines.append("#ifndef MAIASCRIPT_LIB_BUNDLE_H")
    lines.append("#define MAIASCRIPT_LIB_BUNDLE_H")
    lines.append("")
    lines.append("#include <stddef.h>")
    lines.append("")
    lines.append("struct MaiaLibBundleFile {")
    lines.append("    const char *rel_path; // Relative to /sd/lib/ (or /sd/ if starts with ../)")
    lines.append("    const unsigned char *data;")
    lines.append("    size_t len;")
    lines.append("};")
    lines.append("")

    var_names = []
    for idx, (rel, full) in enumerate(files_to_bundle):
        with open(full, "rb") as fp:
            data = fp.read()
        
        var_name = f"s_ms_bundle_{idx}"
        var_names.append((rel, var_name, len(data)))
        
        lines.append(f"// {rel} ({len(data)} bytes)")
        lines.append(f"static const unsigned char {var_name}[] = {{")
        chunk_size = 16
        for c_idx in range(0, len(data), chunk_size):
            chunk = data[c_idx:c_idx+chunk_size]
            hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
            lines.append(f"    {hex_str},")
        lines.append("};\n")

    lines.append("static const struct MaiaLibBundleFile g_maiascript_bundle_files[] = {")
    for rel, vname, length in var_names:
        lines.append(f'    {{ "{rel}", {vname}, {length} }},')
    lines.append("};")
    lines.append("")
    lines.append("static const size_t g_maiascript_bundle_files_count = sizeof(g_maiascript_bundle_files) / sizeof(g_maiascript_bundle_files[0]);")
    lines.append("")
    lines.append("#endif // MAIASCRIPT_LIB_BUNDLE_H\n")

    os.makedirs(os.path.dirname(out_header), exist_ok=True)
    with open(out_header, "w") as fp:
        fp.write("\n".join(lines))

    print(f"Generated {out_header} with {len(files_to_bundle)} bundled files.")

if __name__ == "__main__":
    main()
